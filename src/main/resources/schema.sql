-- car-service database schema.
-- Spring Boot runs this file on every start (spring.sql.init.mode=always),
-- so the tables are recreated each time and then filled from data.sql.

DROP TABLE IF EXISTS car_rent;
DROP TABLE IF EXISTS customer;
DROP TABLE IF EXISTS car;

CREATE TABLE car (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand           VARCHAR(255),
    model           VARCHAR(255),
    vin_code        VARCHAR(255),
    city_based      VARCHAR(255),
    production_year INTEGER,
    image_url       VARCHAR(255),
    created_at      TIMESTAMP,
    updated_at      TIMESTAMP
);

CREATE TABLE customer (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(255),
    email             VARCHAR(255),
    rent_amount_times INTEGER,
    created_at        TIMESTAMP,
    updated_at        TIMESTAMP
);

CREATE TABLE car_rent (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id      BIGINT REFERENCES car (id),
    customer_id BIGINT REFERENCES customer (id),
    start_date  DATE,
    end_date    DATE,
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP
);
